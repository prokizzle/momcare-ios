import SwiftUI

/// Sheet for configuring and sharing a PDF growth report.
@MainActor
struct ExportSheet: View {
    let baby: Baby
    let records: [GrowthRecord]
    let events: [HealthEvent]

    @State private var startDate: Date = Calendar.current.date(byAdding: .month, value: -6, to: .now) ?? .now
    @State private var endDate: Date = .now
    @State private var isGenerating = false
    @State private var exportURL: URL?
    @State private var errorMessage: String?

    private let service = PDFExportService()

    var body: some View {
        NavigationStack {
            Form {
                Section("Date Range") {
                    DatePicker("From", selection: $startDate, in: ...endDate, displayedComponents: .date)
                    DatePicker("To", selection: $endDate, in: startDate..., displayedComponents: .date)
                }

                Section("Report Contents") {
                    Label(
                        "\(filteredRecords.count) growth measurement\(filteredRecords.count == 1 ? "" : "s")",
                        systemImage: "chart.line.uptrend.xyaxis"
                    )
                    Label(
                        "\(filteredEvents.count) health event\(filteredEvents.count == 1 ? "" : "s")",
                        systemImage: "cross.circle"
                    )
                }
                .foregroundStyle(.secondary)

                Section {
                    if isGenerating {
                        HStack {
                            Spacer()
                            ProgressView("Generating report...")
                            Spacer()
                        }
                    } else if let url = exportURL {
                        ShareLink(
                            item: url,
                            subject: Text("\(baby.name) Growth Report"),
                            message: Text("Growth report generated by MomCare"),
                            preview: SharePreview(
                                "\(baby.name) Growth Report",
                                image: Image(systemName: "doc.text.fill")
                            )
                        ) {
                            Label("Share PDF", systemImage: "square.and.arrow.up")
                                .frame(maxWidth: .infinity)
                                .font(MCTypography.headline)
                        }

                        Button("Generate New Report") {
                            exportURL = nil
                        }
                        .foregroundStyle(.secondary)
                    } else {
                        Button {
                            MCHaptic.tap()
                            Task { await generate() }
                        } label: {
                            Label("Generate PDF Report", systemImage: "doc.badge.plus")
                                .frame(maxWidth: .infinity)
                                .font(MCTypography.headline)
                        }
                        .disabled(filteredRecords.isEmpty && filteredEvents.isEmpty)
                    }
                }

                if let errorMessage {
                    Section {
                        Label(errorMessage, systemImage: "exclamationmark.triangle")
                            .foregroundStyle(.red)
                    }
                }
            }
            .navigationTitle("Export Report")
            .navigationBarTitleDisplayMode(.inline)
        }
    }

    // MARK: - Helpers

    private var filteredRecords: [GrowthRecord] {
        records.filter { (startDate...endDate).contains($0.date) }
    }

    private var filteredEvents: [HealthEvent] {
        events.filter { (startDate...endDate).contains($0.date) }
    }

    private func generate() async {
        isGenerating = true
        errorMessage = nil
        defer { isGenerating = false }
        do {
            exportURL = try await service.generateReport(
                baby: baby,
                records: records,
                events: events,
                dateRange: startDate...endDate
            )
        } catch {
            errorMessage = error.localizedDescription
        }
    }
}

#Preview {
    ExportSheet(
        baby: .fixture(),
        records: [.fixture(weightGrams: 4500, lengthCm: 55)],
        events: [.fixture(eventType: .vaccine, title: "DTaP - Dose 1")]
    )
}
